def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def specs(s):
    return sorted(re.findall(r'%(?:\d\$)?(lld|@)', s))


out = sys.argv[1]
T['de'] = {k: v for k, v in KEYS.items()}
bad = 0
for lang, tr in T.items():
    missing = set(KEYS) - set(tr)
    extra = set(tr) - set(KEYS)
    if missing or extra:
        print(lang, 'missing', missing, 'extra', extra); bad += 1
    for k, v in tr.items():
        if k in KEYS and specs(v) != specs(KEYS[k]):
            print(lang, k, 'format mismatch'); bad += 1
    d = os.path.join(out, f'{lang}.lproj')
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, 'Localizable.strings'), 'w', encoding='utf-8') as f:
        f.write(f'/* MacTuner — {lang} */\n\n')
        for k in KEYS:
            if k in tr:
                f.write(f'"{esc(KEYS[k])}" = "{esc(tr[k])}";\n')
print(len(T), 'languages', 'errors:', bad)
sys.exit(1 if bad else 0)
